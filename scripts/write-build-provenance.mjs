import {execFileSync} from 'node:child_process'
import {createHash} from 'node:crypto'
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs'
import {dirname,resolve} from 'node:path'
const root=resolve(new URL('..',import.meta.url).pathname)
const gitDir=process.env.APEX_PROVENANCE_GIT_DIR||resolve(root,'.git')
if(!existsSync(gitDir))throw new Error('Renderer provenance requires an explicit trusted Git directory')
const rels=[
 'src/components/PaperGeneratorSaaS/PTSPaperGenerator.jsx',
 'src/components/PaperGeneratorSaaS/PaperPreviewEngine.jsx',
 'src/components/PaperGeneratorSaaS/paperTemplateCore.jsx',
 'src/components/PaperGeneratorSaaS/UnifiedPaperPreviewEngine.jsx',
 'src/app/globals.css',
]
const sha=b=>createHash('sha256').update(b).digest('hex')
const git=(args,opts={})=>execFileSync('git',[`--git-dir=${gitDir}`,...args],{encoding:opts.encoding??null})
const commit=String(git(['rev-parse','HEAD'],{encoding:'utf8'})).trim()
const rendererFiles={}
for(const rel of rels){
 const live=readFileSync(resolve(root,rel));
 const committed=git(['show',`HEAD:${rel}`]);
 const liveHash=sha(live),commitHash=sha(committed)
 if(liveHash!==commitHash)throw new Error(`Renderer attestation refused: deployed ${rel} does not match Git ${commit}`)
 rendererFiles[rel]=liveHash
}
const data={architectureVersion:'v6-f2-renderer-provenance-2',rendererSourceCommit:commit,attestedPathsOnly:true,rendererPathsMatchCommit:true,rendererFamily:'GENERIC_SAVED_OR_BLANK',rendererRoute:'PTSPaperGenerator/ExistingPerTypeRenderer',rendererFiles}
const out=resolve(root,'src/generated/buildProvenance.ts')
mkdirSync(dirname(out),{recursive:true})
writeFileSync(out,`// generated by scripts/write-build-provenance.mjs; do not edit\nexport const BUILD_PROVENANCE = ${JSON.stringify(data,null,2)} as const\n`)
console.log(JSON.stringify(data))
