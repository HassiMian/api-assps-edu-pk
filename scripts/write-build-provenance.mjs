import {execFileSync} from 'node:child_process'
import {createHash} from 'node:crypto'
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs'
import {dirname,resolve,relative} from 'node:path'
const root=resolve(new URL('..',import.meta.url).pathname)
const rels=[
 'src/components/PaperGeneratorSaaS/PTSPaperGenerator.jsx',
 'src/components/PaperGeneratorSaaS/PaperPreviewEngine.jsx',
 'src/components/PaperGeneratorSaaS/paperTemplateCore.jsx',
 'src/components/PaperGeneratorSaaS/UnifiedPaperPreviewEngine.jsx',
 'src/app/globals.css',
]
const sha=p=>createHash('sha256').update(readFileSync(resolve(root,p))).digest('hex')
const commit=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim()
const dirty=execFileSync('git',['status','--porcelain','--untracked-files=no'],{cwd:root,encoding:'utf8'}).trim()
if(dirty)throw new Error('Refusing provenance generation from a dirty tracked source tree')
const rendererFiles=Object.fromEntries(rels.map(p=>[p,sha(p)]))
const data={architectureVersion:'v6-f2-renderer-provenance-1',sourceCommit:commit,sourceTreeClean:true,rendererFamily:'GENERIC_SAVED_OR_BLANK',rendererRoute:'PTSPaperGenerator/ExistingPerTypeRenderer',rendererFiles}
const out=resolve(root,'src/generated/buildProvenance.ts')
mkdirSync(dirname(out),{recursive:true})
writeFileSync(out,`// generated by scripts/write-build-provenance.mjs; do not edit\nexport const BUILD_PROVENANCE = ${JSON.stringify(data,null,2)} as const\n`)
console.log(JSON.stringify(data))
